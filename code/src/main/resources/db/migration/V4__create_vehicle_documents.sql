CREATE TABLE vehicle_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    document_type VARCHAR(32) NOT NULL,
    document_number VARCHAR(100),
    issue_date DATE,
    expiry_date DATE,
    notes VARCHAR(1000),
    attachment_key VARCHAR(50),
    attachment_media_type VARCHAR(32),
    attachment_size BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_vehicle_document_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicle (id) ON DELETE CASCADE,
    CONSTRAINT chk_vehicle_document_type CHECK (
        document_type IN (
            'INSURANCE', 'PUC', 'REGISTRATION_CERTIFICATE', 'FITNESS_CERTIFICATE',
            'PERMIT', 'DRIVING_LICENCE', 'OTHER'
        )
    ),
    CONSTRAINT chk_vehicle_document_expiry_required CHECK (
        document_type = 'OTHER' OR expiry_date IS NOT NULL
    ),
    CONSTRAINT chk_vehicle_document_date_order CHECK (
        issue_date IS NULL OR expiry_date IS NULL OR expiry_date >= issue_date
    ),
    CONSTRAINT chk_vehicle_document_attachment CHECK (
        (attachment_key IS NULL AND attachment_media_type IS NULL AND attachment_size IS NULL)
        OR
        (attachment_key IS NOT NULL AND attachment_media_type IS NOT NULL AND attachment_size > 0)
    )
);

CREATE INDEX idx_vehicle_document_vehicle_expiry
    ON vehicle_document (vehicle_id, expiry_date);
