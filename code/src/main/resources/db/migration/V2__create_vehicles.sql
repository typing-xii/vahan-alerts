CREATE TABLE vehicle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    nickname VARCHAR(100),
    registration_number VARCHAR(20) NOT NULL,
    vehicle_type VARCHAR(20) NOT NULL,
    make VARCHAR(100),
    model VARCHAR(100),
    manufacturing_year INTEGER,
    fuel_type VARCHAR(20),
    notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_vehicle_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT uk_vehicle_owner_registration UNIQUE (owner_id, registration_number),
    CONSTRAINT chk_vehicle_registration_length CHECK (
        CHAR_LENGTH(registration_number) BETWEEN 3 AND 20
    ),
    CONSTRAINT chk_vehicle_type CHECK (
        vehicle_type IN ('CAR', 'MOTORCYCLE', 'SCOOTER', 'OTHER')
    ),
    CONSTRAINT chk_vehicle_manufacturing_year CHECK (
        manufacturing_year IS NULL OR manufacturing_year BETWEEN 1886 AND 2100
    ),
    CONSTRAINT chk_vehicle_fuel_type CHECK (
        fuel_type IS NULL OR fuel_type IN ('PETROL', 'DIESEL', 'CNG', 'ELECTRIC', 'HYBRID', 'OTHER')
    )
);

CREATE INDEX idx_vehicle_owner_created_at ON vehicle (owner_id, created_at);
