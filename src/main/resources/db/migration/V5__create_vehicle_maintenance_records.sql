CREATE TABLE vehicle_maintenance_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT NOT NULL,
    service_date DATE NOT NULL,
    odometer_km BIGINT NOT NULL,
    service_type VARCHAR(32) NOT NULL,
    workshop_name VARCHAR(150),
    service_cost_inr NUMERIC(12, 2) NOT NULL,
    description VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_vehicle_maintenance_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicle (id) ON DELETE CASCADE,
    CONSTRAINT chk_vehicle_maintenance_odometer CHECK (odometer_km >= 0),
    CONSTRAINT chk_vehicle_maintenance_cost CHECK (service_cost_inr >= 0),
    CONSTRAINT chk_vehicle_maintenance_type CHECK (
        service_type IN (
            'GENERAL_SERVICE', 'ENGINE_OIL_CHANGE', 'BRAKE_SERVICE',
            'TYRE_REPLACEMENT', 'BATTERY_REPLACEMENT', 'REPAIRS', 'OTHER'
        )
    )
);

CREATE INDEX idx_vehicle_maintenance_vehicle_date
    ON vehicle_maintenance_record (vehicle_id, service_date DESC, id DESC);
