CREATE TABLE in_app_notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    vehicle_id BIGINT,
    document_id BIGINT,
    notification_type VARCHAR(32) NOT NULL,
    reminder_offset_days INTEGER NOT NULL,
    document_type_snapshot VARCHAR(32) NOT NULL,
    registration_number_snapshot VARCHAR(20) NOT NULL,
    expiry_date_snapshot DATE NOT NULL,
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_notification_owner FOREIGN KEY (owner_id)
        REFERENCES app_user (id) ON DELETE CASCADE,
    CONSTRAINT fk_notification_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicle (id) ON DELETE SET NULL,
    CONSTRAINT fk_notification_document FOREIGN KEY (document_id)
        REFERENCES vehicle_document (id) ON DELETE SET NULL,
    CONSTRAINT chk_notification_type CHECK (notification_type = 'DOCUMENT_EXPIRY'),
    CONSTRAINT chk_notification_reminder_offset CHECK (
        reminder_offset_days IN (30, 7, 1, 0)
    ),
    CONSTRAINT uk_notification_document_expiry_offset UNIQUE (
        document_id, expiry_date_snapshot, reminder_offset_days
    )
);

CREATE INDEX idx_notification_owner_created
    ON in_app_notification (owner_id, created_at DESC, id DESC);
CREATE INDEX idx_notification_owner_unread
    ON in_app_notification (owner_id, read_at);
